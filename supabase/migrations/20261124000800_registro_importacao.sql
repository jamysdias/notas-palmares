-- Relatório da importação/sincronização feita pelo Apps Script (fica no banco, nenhuma planilha é alterada)
create table public.importacoes (
  id            bigint generated by default as identity primary key,
  em            timestamptz not null default now(),
  tipo          text not null,              -- 'notas' | 'alunos'
  serie         text,
  turma         integer,
  materia       text,
  avaliacoes    integer,
  notas         integer,
  conferidos    integer,
  divergencias  jsonb not null default '[]',
  avisos        jsonb not null default '[]',
  erro          text
);
alter table public.importacoes enable row level security;
revoke all on public.importacoes from anon, authenticated;
grant select on public.importacoes to authenticated;
grant all on public.importacoes to service_role;
create policy leitura on public.importacoes for select to authenticated using (eh_admin());

create or replace function public.registrar_importacao(p jsonb) returns void
language sql security definer set search_path = public as $$
  insert into importacoes (tipo, serie, turma, materia, avaliacoes, notas, conferidos, divergencias, avisos, erro)
  values (coalesce(p->>'tipo','notas'), p->>'serie', nullif(p->>'turma','')::int, p->>'materia',
          nullif(p->>'avaliacoes','')::int, nullif(p->>'notas','')::int, nullif(p->>'conferidos','')::int,
          coalesce(p->'divergencias','[]'), coalesce(p->'avisos','[]'), p->>'erro')
$$;
revoke execute on function public.registrar_importacao(jsonb) from public, anon, authenticated;
grant execute on function public.registrar_importacao(jsonb) to service_role;
