-- =====================================================================
-- Notas Palmares — Estrutura do banco
-- Escala de notas: 0 a 100. Média mínima: 50.
-- =====================================================================

-- ---------- Estrutura escolar ----------
create table public.areas (
  id     smallint generated by default as identity primary key,
  nome   text not null unique,
  ordem  smallint not null default 0
);

create table public.series (
  id        smallint generated by default as identity primary key,
  nome      text not null unique,             -- ex.: '1º ANO', '6º ANO', '1ª SÉRIE'
  segmento  text not null check (segmento in ('Fundamental I','Fundamental II','Ensino Médio')),
  ordem     smallint not null default 0
);

create table public.turmas (
  id        integer generated by default as identity primary key,
  ano       smallint not null,                -- ano letivo
  serie_id  smallint not null references public.series(id),
  numero    smallint not null default 1,      -- 1, 2...
  unique (ano, serie_id, numero)
);

create table public.materias (
  id       integer generated by default as identity primary key,
  nome     text not null unique,
  area_id  smallint not null references public.areas(id)
);

-- Diário = turma × matéria. Pesos da prova bimestral e das contínuas (somam 1).
create table public.diarios (
  id               integer generated by default as identity primary key,
  turma_id         integer not null references public.turmas(id) on delete cascade,
  materia_id       integer not null references public.materias(id),
  peso_bimestral   numeric(4,3) not null default 0 check (peso_bimestral between 0 and 1),
  peso_continuas   numeric(4,3) not null default 1 check (peso_continuas between 0 and 1),
  constraint pesos_somam_1 check (peso_bimestral + peso_continuas = 1),
  unique (turma_id, materia_id)
);

-- ---------- Alunos (fonte oficial: planilha Google, sincronizada) ----------
create table public.alunos (
  ra             text primary key,
  nome           text not null,
  atualizado_em  timestamptz not null default now()
);

create table public.matriculas (
  id         integer generated by default as identity primary key,
  ano        smallint not null,
  aluno_ra   text not null references public.alunos(ra) on update cascade,
  turma_id   integer not null references public.turmas(id),
  numero     smallint,                          -- nº de chamada
  situacao   text not null default 'Ativo' check (situacao in ('Ativo','Transferido')),
  atualizado_em timestamptz not null default now(),
  unique (ano, aluno_ra, turma_id)      -- aluno que troca de turma tem uma matrícula em cada
);
create index on public.matriculas (turma_id);

-- ---------- Usuários e perfis ----------
create table public.usuarios (
  email      text primary key check (email = lower(email)),
  nome       text,
  is_admin   boolean not null default false,
  ativo      boolean not null default true,
  criado_em  timestamptz not null default now()
);

create table public.atribuicoes (            -- professor ↔ diário
  email      text not null references public.usuarios(email) on update cascade on delete cascade,
  diario_id  integer not null references public.diarios(id) on delete cascade,
  primary key (email, diario_id)
);
create index on public.atribuicoes (diario_id);

create table public.coord_series (           -- coordenador de série
  email     text not null references public.usuarios(email) on update cascade on delete cascade,
  serie_id  smallint not null references public.series(id) on delete cascade,
  primary key (email, serie_id)
);

create table public.coord_areas (            -- coordenador de área
  email    text not null references public.usuarios(email) on update cascade on delete cascade,
  area_id  smallint not null references public.areas(id) on delete cascade,
  primary key (email, area_id)
);

-- "Ver como" (modo demonstração): só administradores
create table public.ver_como (
  admin_email  text primary key references public.usuarios(email) on delete cascade,
  alvo_email   text not null references public.usuarios(email) on delete cascade,
  desde        timestamptz not null default now()
);

-- ---------- Calendário ----------
create table public.periodos (
  ano               smallint not null,
  bimestre          smallint not null check (bimestre between 1 and 4),
  inicio            date,
  fim               date,
  prazo_lancamento  date,
  fechado           boolean not null default false,  -- fechado: professor só visualiza
  primary key (ano, bimestre)
);

-- ---------- Avaliações e notas ----------
-- Pacotes: B1–B4 (bimestral), C1–C6 (contínuas), R1–R4 (recuperação), com % que soma 100% por bloco.
create table public.pacotes (
  diario_id   integer not null references public.diarios(id) on delete cascade,
  bimestre    smallint not null check (bimestre between 1 and 4),
  codigo      text not null check (codigo ~ '^(B[1-4]|C[1-6]|R[1-4])$'),
  descricao   text,
  percentual  numeric(5,4) not null default 0 check (percentual between 0 and 1),
  primary key (diario_id, bimestre, codigo)
);

create table public.avaliacoes (
  id          bigint generated by default as identity primary key,
  diario_id   integer not null references public.diarios(id) on delete cascade,
  bimestre    smallint not null check (bimestre between 1 and 4),
  pacote      text not null check (pacote ~ '^(B[1-4]|C[1-6]|R[1-4])$'),
  bloco       char(1) generated always as (left(pacote,1)) stored,
  nome        text not null,
  data        date,
  peso        numeric(3,1) not null default 1 check (peso between 0 and 9),
  ordem       integer not null default 0,
  criado_por  text,
  criado_em   timestamptz not null default now()
);
create index on public.avaliacoes (diario_id, bimestre);

create table public.notas (
  avaliacao_id   bigint not null references public.avaliacoes(id) on delete cascade,
  aluno_ra       text not null references public.alunos(ra) on update cascade,
  valor          numeric(5,2) check (valor between 0 and 100),
  nao_avaliado   boolean not null default false,          -- o "-" das planilhas
  atualizado_por text,
  atualizado_em  timestamptz not null default now(),
  primary key (avaliacao_id, aluno_ra),
  constraint valor_ou_traco check (not (valor is not null and nao_avaliado))
);
create index on public.notas (aluno_ra);

-- Ajustes por aluno no bimestre. Nada aqui apaga a média calculada: o resultado final é derivado.
create table public.ajustes (
  diario_id               integer not null references public.diarios(id) on delete cascade,
  bimestre                smallint not null check (bimestre between 1 and 4),
  aluno_ra                text not null references public.alunos(ra) on update cascade,
  acrescimo               numeric(2,1) check (acrescimo between 0 and 0.9),   -- professor
  conselho                numeric(5,2) check (conselho between 0 and 100),    -- coordenação
  conselho_justificativa  text,
  bonus                   numeric(4,2) check (bonus between 0 and 10),        -- coordenação
  bonus_justificativa     text,
  atualizado_por          text,
  atualizado_em           timestamptz not null default now(),
  primary key (diario_id, bimestre, aluno_ra)
);

-- ---------- Auditoria ----------
create table public.auditoria (
  id        bigint generated by default as identity primary key,
  em        timestamptz not null default now(),
  usuario   text,          -- quem estava logado de verdade
  como      text,          -- perfil efetivo (difere quando admin usa "ver como")
  tabela    text not null,
  operacao  text not null,
  chave     jsonb,
  antes     jsonb,
  depois    jsonb
);
create index on public.auditoria (tabela, em desc);
create index on public.auditoria using gin (chave);
